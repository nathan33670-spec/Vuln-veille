EVENTS_SECONDS = 600
POLL_SECONDS = 1.0
TERMINAL = ("succeeded", "failed")


def now() -> datetime:
    return datetime.now(UTC)


async def _audit(
    db: AsyncSession,
    request: Request,
    access: WorkspaceAccess,
    action: str,
    target: str,
    **data: Any,
) -> None:
    await record(
        db,
        access.principal.audit_ctx(request),
        AuditEntry(
            action=action,
            target_type="bulletin",
            target_id=target,
            workspace_id=access.workspace.id,
            details=data,
        ),
    )


def _queue(request: Request, draft: DraftRequest) -> None:
    tasks: TaskQueue = request.app.state.tasks
    tasks.send(DRAFT_TASK, {"request_id": str(draft.id), "workspace_id": str(draft.workspace_id)})


async def _rate(request: Request, access: WorkspaceAccess) -> None:
    limiter: RateLimiter = request.app.state.rate_limiter
    if not await limiter.hit("bulletin_draft", str(access.principal.user_id), 30, 3600):
        raise HTTPException(status_code=429, detail="rate_limited")


async def _settings(db: AsyncSession, workspace_id: uuid.UUID) -> BulletinSettings | None:
    return await db.get(BulletinSettings, workspace_id)


async def _own(db: AsyncSession, access: WorkspaceAccess, bulletin_id: uuid.UUID) -> Bulletin:
    bulletin = await db.get(Bulletin, bulletin_id)
    if bulletin is None or bulletin.workspace_id != access.workspace.id:
        raise HTTPException(status_code=404, detail="not_found")
    return bulletin


async def _locked(
    db: AsyncSession, access: WorkspaceAccess, bulletin_id: uuid.UUID, version: int
) -> Bulletin:
    bulletin = await _own(db, access, bulletin_id)
    await db.refresh(bulletin, with_for_update=True)
    if bulletin.version != version:
        raise HTTPException(status_code=409, detail="version_conflict")
    return bulletin


async def _template_of(
    db: AsyncSession, version_id: uuid.UUID
) -> tuple[BulletinTemplate, BulletinTemplateVersion]:
    version = await db.get(BulletinTemplateVersion, version_id)
    assert version is not None  # noqa: S101 - foreign key
    template = await db.get(BulletinTemplate, version.template_id)
    assert template is not None  # noqa: S101 - foreign key
    return template, version


def _summary(r: BulletinRevision) -> RevisionSummaryOut:
    return RevisionSummaryOut(
        rev_no=r.rev_no,
        created_by_type=r.created_by_type,
        created_by=r.created_by,
        agent_run_id=r.agent_run_id,
        change_note=r.change_note,
        content_hash=r.content_hash,
        created_at=r.created_at,
    )


def _revision_out(r: BulletinRevision) -> RevisionOut:
    return RevisionOut(
        **_summary(r).model_dump(),
        fields=r.fields,
        rendered_markdown=r.rendered_markdown,
        rendered_html=r.rendered_html,
    )


async def _rev_no(db: AsyncSession, revision_id: uuid.UUID | None) -> int | None:
    if revision_id is None:
        return None
    revision = await db.get(BulletinRevision, revision_id)
    return revision.rev_no if revision else None


async def _bulletin_out(
    db: AsyncSession, bulletin: Bulletin, access: WorkspaceAccess
) -> BulletinOut:
    workspace = await db.get(Workspace, bulletin.workspace_id)
    return BulletinOut(
        id=bulletin.id,
        ref=bulletin.ref,
        title=bulletin.title,
        status=bulletin.status,
        severity=bulletin.severity,
        tlp=bulletin.tlp,
        language=bulletin.language,
        workspace_slug=workspace.slug if workspace else "",
        own=bulletin.workspace_id == access.workspace.id,
        author_id=bulletin.author_id,
        current_rev_no=await _rev_no(db, bulletin.current_revision_id),
        published_rev_no=await _rev_no(db, bulletin.published_revision_id),
        published_at=bulletin.published_at,
        updated_at=bulletin.updated_at,
        version=bulletin.version,
    )


def _linked(b: Bulletin) -> LinkedBulletinOut:
    return LinkedBulletinOut(id=b.id, ref=b.ref, language=b.language, status=b.status)


async def _detail(
    db: AsyncSession, bulletin: Bulletin, access: WorkspaceAccess
) -> BulletinDetailOut:
    own = bulletin.workspace_id == access.workspace.id
    template, version = (
        await _template_of(db, bulletin.template_version_id) if own else (None, None)
    )
    # The other team only sees what was published.
    shown_id = bulletin.current_revision_id if own else bulletin.published_revision_id
    current = await db.get(BulletinRevision, shown_id) if shown_id else None
    revisions = (
        list(
            (
                await db.execute(
                    select(BulletinRevision)
                    .where(BulletinRevision.bulletin_id == bulletin.id)
                    .order_by(BulletinRevision.rev_no.desc())
                )
            ).scalars()
        )
        if own
        else []
    )
    vulns = (
        await db.execute(
            select(Vulnerability)
            .join(BulletinVulnerability, BulletinVulnerability.vulnerability_id == Vulnerability.id)
            .where(BulletinVulnerability.bulletin_id == bulletin.id)
        )
    ).scalars()
    techs = (
        await db.execute(
            select(Technology)
            .join(BulletinTechnology, BulletinTechnology.technology_id == Technology.id)
            .where(BulletinTechnology.bulletin_id == bulletin.id)
            .order_by(Technology.display_name)
        )
    ).scalars()
    audiences = (
        await db.execute(
            select(BulletinAudience.client_org_id).where(
                BulletinAudience.bulletin_id == bulletin.id
            )
        )
    ).scalars()
    source = await db.get(Bulletin, bulletin.translation_of) if bulletin.translation_of else None
    translations = (
        await db.execute(select(Bulletin).where(Bulletin.translation_of == bulletin.id))
    ).scalars()
    settings = await _settings(db, bulletin.workspace_id) if own else None
    return BulletinDetailOut(
        **(await _bulletin_out(db, bulletin, access)).model_dump(),
        audience_type=bulletin.audience_type,
        audience_org_ids=list(audiences) if own else [],
        template_id=template.id if template else None,
        template_name=template.name if template else None,
        template_version_no=version.version_no if version else None,
        template_spec=version.spec if version else None,
        review_required=bool(settings and settings.review_required),
        submitted_by=bulletin.submitted_by if own else None,
        reviewer_id=bulletin.reviewer_id if own else None,
        approved_at=bulletin.approved_at if own else None,
        withdrawn_reason=bulletin.withdrawn_reason if own else None,
        current=_revision_out(current) if current else None,
        revisions=[_summary(r) for r in revisions],
        vulnerabilities=[
            LinkedVulnerabilityOut(id=v.id, ref=v.ref, cve_id=v.cve_id, title=v.title)
            for v in vulns
        ],
        technologies=[LinkedTechnologyOut(id=t.id, display_name=t.display_name) for t in techs],
        translation_of=_linked(source) if source else None,
        translations=[_linked(t) for t in translations],
    )


async def _draft_out(db: AsyncSession, draft: DraftRequest) -> DraftRequestOut:
    name, version_no = None, None
    if draft.template_version_id:
        template, version = await _template_of(db, draft.template_version_id)
        name, version_no = template.name, version.version_no
    return DraftRequestOut(
        id=draft.id,
        kind=draft.kind,
        status=draft.status,
        progress=draft.progress,
        bulletin_id=draft.bulletin_id,
        agent_run_id=draft.agent_run_id,
        error=draft.error,
        template_name=name,
        template_version_no=version_no,
        selection_reasons=list(draft.input.get("selection_reasons") or []),
        requested_by=draft.requested_by,
        created_at=draft.created_at,
        finished_at=draft.finished_at,
    )


async def _choose_template(
    db: AsyncSession,
    access: WorkspaceAccess,
    template_id: uuid.UUID | None,
    vulnerability_ids: list[uuid.UUID],
    language: str | None,
) -> tuple[uuid.UUID, list[str]]:
    """The template version to apply: the one asked for, else the rules (spec 04 §2)."""
    candidates = await active_candidates(db, access.workspace.id)
    if template_id is not None:
        chosen = next((c for c in candidates if c.template_id == template_id), None)
        if chosen is None:
            raise HTTPException(status_code=422, detail="template_not_active")
        return chosen.version_id, []
    settings = await _settings(db, access.workspace.id)
    default_id = settings.default_template_id if settings else None
    selection: Selection | None = None
    facts = (
        await vulnerability_facts(db, access.workspace.id, vulnerability_ids[0])
        if vulnerability_ids
        else None
    )
    if facts is not None:
        selection = select_template(
            candidates, facts, default_template_id=default_id, language=language
        )
    else:
        default = fallback_template(
            [c for c in candidates if language is None or c.spec.language == language],
            default_id,
        )
        selection = Selection(default, None) if default else None
    if selection is None:
        raise HTTPException(status_code=422, detail="no_template")
    return selection.candidate.version_id, selection.reasons


def _routes_drafts(router: APIRouter) -> None:
    @router.post("/draft-requests", response_model=DraftRequestOut, status_code=202)
    async def request_draft(
        body: DraftRequestIn, request: Request, access: Drafter, db: DB
    ) -> DraftRequestOut:
        if not (body.vulnerability_ids or body.cve_id or body.urls or body.text.strip()):
            raise HTTPException(status_code=422, detail="no_input")
        if any(not u.lower().startswith(("https://", "http://")) for u in body.urls):
            raise HTTPException(status_code=422, detail="invalid_url")
        await _rate(request, access)
        moment = now()
        vulnerability_ids = list(dict.fromkeys(body.vulnerability_ids))
        for vulnerability_id in vulnerability_ids:
            if await db.get(Vulnerability, vulnerability_id) is None:
                raise HTTPException(status_code=422, detail="vulnerability_not_found")
        if body.cve_id:
            # A CVE not followed yet becomes an unqualified vulnerability (spec 04 §3).
            vulnerability, _ = await create_vulnerability(
                db, now=moment, workspace_id=access.workspace.id,
                actor=access.principal.user_id, origin="user", cve_id=body.cve_id,
            )  # fmt: skip
            team = await db.execute(
                select(Assessment.id).where(
                    Assessment.vulnerability_id == vulnerability.id,
                    Assessment.workspace_id == access.workspace.id,
                )
            )
            if team.scalar_one_or_none() is None:
                db.add(
                    Assessment(
                        id=uuid.uuid4(), vulnerability_id=vulnerability.id,
                        workspace_id=access.workspace.id, status="new", rationale="", version=1,
                    )
                )  # fmt: skip
            if vulnerability.id not in vulnerability_ids:
                vulnerability_ids.insert(0, vulnerability.id)
            await db.flush()
        version_id, reasons = await _choose_template(
            db, access, body.template_id, vulnerability_ids, body.language
        )
        draft = DraftRequest(
            id=uuid7(),
            workspace_id=access.workspace.id,
            kind="draft",
            requested_by=access.principal.user_id,
            input={
                "vulnerability_ids": [str(v) for v in vulnerability_ids],
                "urls": body.urls,
                "text": body.text,
                "selection_reasons": reasons,
            },
            template_version_id=version_id,
            extra_instructions=body.extra_instructions,
            status="queued",
            progress=[],
            created_at=moment,
        )
        db.add(draft)
        await _audit(db, request, access, "bulletin.draft_requested", str(draft.id))
        await db.commit()
        _queue(request, draft)
        return await _draft_out(db, draft)

    @router.get("/draft-requests", response_model=list[DraftRequestOut])
    async def list_drafts(access: Drafter, db: DB) -> list[DraftRequestOut]:
        rows = (
            await db.execute(
                select(DraftRequest)
                .where(DraftRequest.workspace_id == access.workspace.id)
                .order_by(DraftRequest.created_at.desc())
                .limit(50)
            )
        ).scalars()
        return [await _draft_out(db, d) for d in rows]

    @router.get("/draft-requests/{request_id}", response_model=DraftRequestOut)
    async def get_draft(request_id: uuid.UUID, access: Drafter, db: DB) -> DraftRequestOut:
        draft = await db.get(DraftRequest, request_id)
        if draft is None or draft.workspace_id != access.workspace.id:
            raise HTTPException(status_code=404, detail="not_found")
        return await _draft_out(db, draft)

    @router.get("/draft-requests/{request_id}/events")
    async def draft_events(
        request_id: uuid.UUID, request: Request, access: Drafter, db: DB
    ) -> StreamingResponse:
        """Server-sent events: ``progress`` at each step, then ``done`` (polls the
        database, holds no transaction; ten minutes at most)."""
        draft = await db.get(DraftRequest, request_id)
        if draft is None or draft.workspace_id != access.workspace.id:
            raise HTTPException(status_code=404, detail="not_found")
        context = get_context(db)
        sessions: async_sessionmaker[AsyncSession] = request.app.state.sessionmaker

        async def stream() -> AsyncIterator[str]:
            seen = -1
            async with sessions() as session:
                init_context(session)
                await set_context(session, **asdict(context))
                for _ in range(int(EVENTS_SECONDS / POLL_SECONDS)):
                    if await request.is_disconnected():
                        return
                    current = await session.get(DraftRequest, request_id, populate_existing=True)
                    if current is None:
                        return
                    if len(current.progress) != seen:
                        seen = len(current.progress)
                        out = await _draft_out(session, current)
                        yield _sse("progress", out.model_dump(mode="json"))
                    await session.commit()
                    if current.status in TERMINAL:
                        yield _sse("done", {"status": current.status, "error": current.error})
                        return
                    await asyncio.sleep(POLL_SECONDS)

        return StreamingResponse(
            stream(),
            media_type="text/event-stream",
            headers={"cache-control": "no-store", "x-accel-buffering": "no"},
        )


def _sse(event: str, data: dict[str, Any]) -> str:
    return f"event: {event}\ndata: {json.dumps(data, ensure_ascii=False)}\n\n"


async def _spec(db: AsyncSession, bulletin: Bulletin) -> TemplateSpec:
    _, version = await _template_of(db, bulletin.template_version_id)
    return parse_spec(version.spec)


def _routes_bulletins(router: APIRouter) -> None:
    @router.get("/bulletins", response_model=list[BulletinOut])
    async def list_bulletins(
        access: Drafter,
        db: DB,
        status: Annotated[str | None, Query(max_length=20)] = None,
        scope: Annotated[str, Query(pattern=r"^(own|shared)$")] = "own",
    ) -> list[BulletinOut]:
        """``own``: the workspace's bulletins; ``shared``: those the other team published."""
        query = select(Bulletin).order_by(Bulletin.updated_at.desc()).limit(200)
        if scope == "own":
            query = query.where(Bulletin.workspace_id == access.workspace.id)
        else:
            query = query.where(
                Bulletin.workspace_id != access.workspace.id,
                Bulletin.published_revision_id.is_not(None),
                Bulletin.status != "withdrawn",
            )
        if status:
            query = query.where(Bulletin.status == status)
        return [await _bulletin_out(db, b, access) for b in (await db.execute(query)).scalars()]

    @router.get("/bulletin-audiences", response_model=list[AudienceOut])
    async def list_audiences(access: Drafter, db: DB) -> list[AudienceOut]:
        """The client organisations a bulletin can be addressed to (name only)."""
        del access  # the permission is the check
        rows = await db.execute(
            select(ClientOrganization)
            .where(ClientOrganization.status == "active")
            .order_by(ClientOrganization.name)
        )
        return [AudienceOut(id=o.id, name=o.name) for o in rows.scalars()]

    @router.get("/bulletins/{bulletin_id}", response_model=BulletinDetailOut)
    async def get_bulletin(bulletin_id: uuid.UUID, access: Drafter, db: DB) -> BulletinDetailOut:
        bulletin = await db.get(Bulletin, bulletin_id)
        visible = bulletin is not None and (
            bulletin.workspace_id == access.workspace.id
            or (bulletin.published_revision_id is not None and bulletin.status != "withdrawn")
        )
        if bulletin is None or not visible:
            raise HTTPException(status_code=404, detail="not_found")
        return await _detail(db, bulletin, access)

    @router.get("/bulletins/{bulletin_id}/revisions/{rev_no}", response_model=RevisionOut)
    async def get_revision(
        bulletin_id: uuid.UUID, rev_no: int, access: Drafter, db: DB
    ) -> RevisionOut:
        bulletin = await _own(db, access, bulletin_id)
        revision = (
            await db.execute(
                select(BulletinRevision).where(
                    BulletinRevision.bulletin_id == bulletin.id, BulletinRevision.rev_no == rev_no
                )
            )
        ).scalar_one_or_none()
        if revision is None:
            raise HTTPException(status_code=404, detail="not_found")
        return _revision_out(revision)

    @router.post(
        "/bulletins/{bulletin_id}/revisions", response_model=BulletinDetailOut, status_code=201
    )
    async def edit_bulletin(
        bulletin_id: uuid.UUID, body: RevisionIn, request: Request, access: Drafter, db: DB
    ) -> BulletinDetailOut:
        bulletin = await _own(db, access, bulletin_id)
        await db.refresh(bulletin, with_for_update=True)
        ensure_editable(bulletin)
        if await _rev_no(db, bulletin.current_revision_id) != body.base_rev_no:
            raise HTTPException(status_code=409, detail="version_conflict")
        spec = await _spec(db, bulletin)
        fields, errors = clean_fields(spec, body.fields)
        if errors:
            raise ApiError(422, "invalid_fields", errors)
        revision = await add_revision(
            db, bulletin, spec, fields, by_type="user", by=access.principal.user_id,
            agent_run_id=None, note=body.change_note, now=now(),
        )  # fmt: skip
        after_edit(bulletin)
        bulletin.version += 1
        await _audit(
            db, request, access, "bulletin.edited", str(bulletin.id), rev_no=revision.rev_no
        )
        await db.commit()
        return await _detail(db, bulletin, access)

    @router.patch("/bulletins/{bulletin_id}", response_model=BulletinDetailOut)
    async def update_bulletin(
        bulletin_id: uuid.UUID, body: BulletinUpdate, request: Request, access: Drafter, db: DB
    ) -> BulletinDetailOut:
        """Marking and audience (spec 04, 6.7): a change is reviewed again; a TLP change
        is a new revision, the marking being part of the rendered bulletin."""
        bulletin = await _locked(db, access, bulletin_id, body.version)
        ensure_editable(bulletin)
        changed: list[str] = []
        if body.audience_org_ids is not None:
            known = set(
                (
                    await db.execute(
                        select(ClientOrganization.id).where(
                            ClientOrganization.id.in_(body.audience_org_ids)
                        )
                    )
                ).scalars()
            )
            if known != set(body.audience_org_ids):
                raise HTTPException(status_code=422, detail="client_not_found")
            await db.execute(
                delete(BulletinAudience).where(BulletinAudience.bulletin_id == bulletin.id)
            )
            if known:
                await db.execute(
                    insert(BulletinAudience),
                    [
                        {
                            "bulletin_id": bulletin.id,
                            "client_org_id": c,
                            "workspace_id": bulletin.workspace_id,
                        }
                        for c in sorted(known)
                    ],
                )
            changed.append("audience")
        if body.audience_type is not None and body.audience_type != bulletin.audience_type:
            bulletin.audience_type = body.audience_type
            changed.append("audience_type")
        if body.tlp is not None and body.tlp != bulletin.tlp:
            bulletin.tlp = body.tlp
            current = await db.get(BulletinRevision, bulletin.current_revision_id)
            assert current is not None  # noqa: S101 - every bulletin has one
            await add_revision(
                db, bulletin, await _spec(db, bulletin), current.fields, by_type="user",
                by=access.principal.user_id, agent_run_id=None, note=f"TLP:{body.tlp}", now=now(),
            )  # fmt: skip
            changed.append("tlp")
        if changed:
            after_edit(bulletin)
            bulletin.version += 1
            bulletin.updated_at = now()
            await _audit(db, request, access, "bulletin.updated", str(bulletin.id), fields=changed)
        await db.commit()
        return await _detail(db, bulletin, access)

    @router.post(
        "/bulletins/{bulletin_id}/regenerate", response_model=DraftRequestOut, status_code=202
    )
    async def regenerate_field(
        bulletin_id: uuid.UUID, body: RegenerateIn, request: Request, access: Drafter, db: DB
    ) -> DraftRequestOut:
        bulletin = await _own(db, access, bulletin_id)
        ensure_editable(bulletin)
        field = (await _spec(db, bulletin)).field(body.field)
        if field is None or field.generation.mode != "ai":
            raise HTTPException(status_code=422, detail="field_not_generated")
        await _rate(request, access)
        draft = DraftRequest(
            id=uuid7(), workspace_id=access.workspace.id, kind="field",
            requested_by=access.principal.user_id,
            input={"bulletin_id": str(bulletin.id), "field": body.field},
            template_version_id=bulletin.template_version_id,
            extra_instructions=body.instructions, status="queued", progress=[], created_at=now(),
        )  # fmt: skip
        db.add(draft)
        await _audit(
            db,
            request,
            access,
            "bulletin.field_regeneration_requested",
            str(bulletin.id),
            field=body.field,
        )
        await db.commit()
        _queue(request, draft)
        return await _draft_out(db, draft)

    @router.post(
        "/bulletins/{bulletin_id}/translations", response_model=DraftRequestOut, status_code=202
    )
    async def translate(
        bulletin_id: uuid.UUID, body: TranslateIn, request: Request, access: Drafter, db: DB
    ) -> DraftRequestOut:
        """The FR/EN version (Q10), from the validated text, as a new linked draft."""
        bulletin = await _own(db, access, bulletin_id)
        if bulletin.status not in ("approved", "published"):
            raise HTTPException(status_code=409, detail="not_approved")
        if body.language == bulletin.language:
            raise HTTPException(status_code=422, detail="same_language")
        vulns = list(
            (
                await db.execute(
                    select(BulletinVulnerability.vulnerability_id).where(
                        BulletinVulnerability.bulletin_id == bulletin.id
                    )
                )
            ).scalars()
        )
        version_id, reasons = await _choose_template(
            db, access, body.template_id, vulns, body.language
        )
        await _rate(request, access)
        draft = DraftRequest(
            id=uuid7(), workspace_id=access.workspace.id, kind="translation",
            requested_by=access.principal.user_id,
            input={"bulletin_id": str(bulletin.id), "selection_reasons": reasons},
            template_version_id=version_id, status="queued", progress=[], created_at=now(),
        )  # fmt: skip
        db.add(draft)
        await _audit(
            db,
            request,
            access,
            "bulletin.translation_requested",
            str(bulletin.id),
            language=body.language,
        )
        await db.commit()
        _queue(request, draft)
        return await _draft_out(db, draft)

    async def _actor(db: AsyncSession, access: WorkspaceAccess) -> Actor:
        settings = await _settings(db, access.workspace.id)
        return Actor(access.principal.user_id, bool(settings and settings.review_required))

    async def _transition(
        db: AsyncSession, request: Request, access: WorkspaceAccess, bulletin: Bulletin,
        action: str, **data: Any,
    ) -> BulletinDetailOut:  # fmt: skip
        bulletin.version += 1
        bulletin.updated_at = now()
        await _audit(
            db, request, access, f"bulletin.{action}", str(bulletin.id),
            rev_no=await _rev_no(db, bulletin.current_revision_id), **data,
        )  # fmt: skip
        await db.commit()
        return await _detail(db, bulletin, access)

    @router.post("/bulletins/{bulletin_id}/submit", response_model=BulletinDetailOut)
    async def submit_bulletin(
        bulletin_id: uuid.UUID, body: TransitionIn, request: Request, access: Drafter, db: DB
    ) -> BulletinDetailOut:
        bulletin = await _locked(db, access, bulletin_id, body.version)
        submit(bulletin, await _actor(db, access))
        return await _transition(db, request, access, bulletin, "submitted", comment=body.comment)

    @router.post("/bulletins/{bulletin_id}/reject", response_model=BulletinDetailOut)
    async def reject_bulletin(
        bulletin_id: uuid.UUID, body: TransitionIn, request: Request, access: Reviewer, db: DB
    ) -> BulletinDetailOut:
        bulletin = await _locked(db, access, bulletin_id, body.version)
        reject(bulletin, await _actor(db, access))
        return await _transition(db, request, access, bulletin, "rejected", comment=body.comment)

    @router.post("/bulletins/{bulletin_id}/approve", response_model=BulletinDetailOut)
    async def approve_bulletin(
        bulletin_id: uuid.UUID, body: TransitionIn, request: Request, access: Reviewer, db: DB
    ) -> BulletinDetailOut:
        bulletin = await _locked(db, access, bulletin_id, body.version)
        approve(bulletin, await _actor(db, access), now())
        return await _transition(db, request, access, bulletin, "approved", comment=body.comment)

    @router.post("/bulletins/{bulletin_id}/publish", response_model=BulletinDetailOut)
    async def publish_bulletin(
        bulletin_id: uuid.UUID,
        body: TransitionIn,
        request: Request,
        access: Publisher,
        db: DB,
        settings: SettingsDep,
    ) -> BulletinDetailOut:
        """Publication needs a recent second factor; the published revision is frozen."""
        ensure_recent_step_up(access.principal, settings)
        bulletin = await _locked(db, access, bulletin_id, body.version)
        publish(bulletin, await _actor(db, access), now())
        current = await db.get(BulletinRevision, bulletin.current_revision_id)
        return await _transition(
            db, request, access, bulletin, "published",
            content_hash=current.content_hash if current else None,
        )  # fmt: skip

    @router.post("/bulletins/{bulletin_id}/withdraw", response_model=BulletinDetailOut)
    async def withdraw_bulletin(
        bulletin_id: uuid.UUID,
        body: WithdrawIn,
        request: Request,
        access: Publisher,
        db: DB,
        settings: SettingsDep,
    ) -> BulletinDetailOut:
        ensure_recent_step_up(access.principal, settings)
        bulletin = await _locked(db, access, bulletin_id, body.version)
        withdraw(bulletin, body.reason, now())
        return await _transition(db, request, access, bulletin, "withdrawn", reason=body.reason)


def build_bulletins_router() -> APIRouter:
    router = APIRouter(tags=["bulletins"])
    workspace = APIRouter(prefix="/workspaces/{workspace}")
    _routes_drafts(workspace)
    _routes_bulletins(workspace)
    router.include_router(workspace)
    return router

"""Egress allow-list of the smokescreen proxy, derived from connector declarations.

Static domains come from the registered types; types reading user-provided URLs
(RSS, web pages, generic APIs) add the domains of their enabled connectors.
``python -m app.cli egress-acl`` writes the file; smokescreen reloads it on restart.

Private ranges are refused by smokescreen itself, whatever the allow-list: with
``--config-output`` the command also writes smokescreen's configuration, whose
``allow_ranges`` holds the ranges an administrator approved for enabled connectors
(publication, self-hosted AI engines: ADR-030, ADR-032), exactly as the workers apply
them.
"""

from collections.abc import Iterable

from sqlalchemy import select

from app.connectors.base import registered
from app.connectors.models import Connector
from app.connectors.runtime import approved_networks
from app.core.config import Settings
from app.core.db import create_engine, create_sessionmaker
from app.core.rls import init_context, set_context

HEADER = """\
# Generated by `python -m app.cli egress-acl` from the connector declarations
# (spec 07 section 1). Do not edit by hand: declare domains in the connector types.
---
version: v1
services: []
default:
  name: vuln-veille-workers
  project: vuln-veille
  action: enforce
  allowed_domains:
"""


def static_domains() -> set[str]:
    return {domain for type_ in registered().values() for domain in type_.egress_domains}


async def connector_domains(settings: Settings) -> set[str]:
    """Domains of every enabled connector, all scopes (worker role, admin context)."""
    engine = create_engine(settings.database_url_worker.get_secret_value())
    try:
        async with create_sessionmaker(engine)() as db:
            init_context(db)
            await set_context(db, is_platform_admin=True)
            rows = await db.execute(select(Connector.egress_domains).where(Connector.enabled))
            return {domain for (domains,) in rows.all() for domain in domains}
    finally:
        await engine.dispose()


CONFIG = """\
# smokescreen configuration (ADR-012), generated by `python -m app.cli egress-acl
# --config-output`. Private, loopback, link-local (incl. cloud metadata) and other
# non-routable ranges are refused by smokescreen itself, except the ranges below,
# approved by a platform administrator for a connector (ADR-030, ADR-032).
acl_file: /etc/smokescreen/acl.yaml
# Clients without an mTLS role use the "default" ACL entry (per-worker roles: phase 2).
allow_missing_role: true
deny_ranges:
  - 100.64.0.0/10   # carrier-grade NAT
  - 198.18.0.0/15   # benchmarking
connect_timeout: 10s
idle_timeout: 60s
max_concurrent_requests: 200
"""


async def approved_ranges(settings: Settings) -> set[str]:
    """Private ranges approved for the enabled connectors, as the workers apply them
    (the latest decision covers the connector's current hosts and ranges)."""
    engine = create_engine(settings.database_url_worker.get_secret_value())
    try:
        async with create_sessionmaker(engine)() as db:
            init_context(db)
            await set_context(db, is_platform_admin=True)
            connectors = list(
                (
                    await db.execute(
                        select(Connector).where(Connector.enabled, Connector.allow_private_network)
                    )
                ).scalars()
            )
            ranges: set[str] = set()
            for connector in connectors:
                # The decisions of a workspace connector are read in its workspace (RLS).
                workspaces = (connector.workspace_id,) if connector.workspace_id else ()
                await set_context(db, workspace_ids=workspaces)
                hosts = tuple(connector.egress_domains)
                ranges |= {str(n) for n in await approved_networks(db, connector, hosts)}
            return ranges
    finally:
        await engine.dispose()


def render_config(ranges: Iterable[str]) -> str:
    # Ranges come from validated CIDR columns: safe to emit as plain YAML scalars.
    allowed = sorted(set(ranges))
    if not allowed:
        return CONFIG
    return CONFIG + "allow_ranges:\n" + "".join(f"  - {r}\n" for r in allowed)


def render_acl(domains: Iterable[str]) -> str:
    # Domains were validated by the connector types: safe to emit as plain YAML scalars.
    return HEADER + "".join(f"    - {domain}\n" for domain in sorted(set(domains)))

"""Egress allow-list of the smokescreen proxy, derived from connector declarations.

Static domains come from the registered types; types reading user-provided URLs
(RSS, web pages, generic APIs) add the domains of their enabled connectors.
``python -m app.cli egress-acl`` writes the file; smokescreen reloads it on restart.
"""

from collections.abc import Iterable

from sqlalchemy import select

from app.connectors.base import registered
from app.connectors.models import Connector
from app.core.config import Settings
from app.core.db import create_engine, create_sessionmaker
from app.core.rls import init_context, set_context

HEADER = """\
# Generated by `python -m app.cli egress-acl` from the connector declarations
# (spec 07 section 1). Do not edit by hand: declare domains in the connector types.
---
version: v1
services: []
default:
  name: vuln-veille-workers
  project: vuln-veille
  action: enforce
  allowed_domains:
"""


def static_domains() -> set[str]:
    return {domain for type_ in registered().values() for domain in type_.egress_domains}


async def connector_domains(settings: Settings) -> set[str]:
    """Domains of every enabled connector, all scopes (worker role, admin context)."""
    engine = create_engine(settings.database_url_worker.get_secret_value())
    try:
        async with create_sessionmaker(engine)() as db:
            init_context(db)
            await set_context(db, is_platform_admin=True)
            rows = await db.execute(select(Connector.egress_domains).where(Connector.enabled))
            return {domain for (domains,) in rows.all() for domain in domains}
    finally:
        await engine.dispose()


def render_acl(domains: Iterable[str]) -> str:
    # Domains were validated by the connector types: safe to emit as plain YAML scalars.
    return HEADER + "".join(f"    - {domain}\n" for domain in sorted(set(domains)))
